"""Listen brand: one bar table drives the tray icons, the app icon files and the in-app logo; the name is Listen.

No window, input or device is touched. If brand/ exists (it is not copied into the isolated runner), its SVGs are checked too.
"""
import ast
import io
from pathlib import Path
import re
import sys

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
source_text = (ROOT / 'dictate.py').read_text(encoding='utf-8')
tree = ast.parse(source_text)
wanted = [n for n in tree.body
          if (isinstance(n, ast.FunctionDef) and n.name == 'level_icon')
          or (isinstance(n, ast.Assign) and any(getattr(t, 'id', '') in ('LEVEL_BARS', 'LEVEL_BAR_WIDTH') for t in n.targets))]
assert len(wanted) == 3, 'LEVEL_BARS, LEVEL_BAR_WIDTH and level_icon must exist in dictate.py'
ns = {'Image': Image, 'ImageDraw': ImageDraw}
exec(compile(ast.Module(body=wanted, type_ignores=[]), '<level_icon>', 'exec'), ns)
bars, width, level_icon = ns['LEVEL_BARS'], ns['LEVEL_BAR_WIDTH'], ns['level_icon']
BLUE = '#5B8CFF'

# 1. The mark itself: five bars, one loud, accurate colours, transparent corners on the tile.
assert len(bars) == 5 and sum(1 for b in bars if b[3] is None) == 1 and bars[2][3] is None, 'the centre bar is the loud one'
icon = level_icon(BLUE, tile=True, size=256)
assert icon.size == (256, 256) and icon.mode == 'RGBA'
assert icon.getpixel((128, 128)) == (91, 140, 255, 255), icon.getpixel((128, 128))
assert icon.getpixel((1, 1))[3] == 0, 'tile corners must be transparent'
side = icon.getpixel((int((9 + width / 2) * 4), 128))
assert side[3] == 255 and side[0] > 100, 'side bars sit on the tile as semi-opaque off-white, not see-through'
bare = level_icon('#E5484D', tile=False, size=64)
assert bare.getpixel((32, 32))[:3] == (229, 72, 77) and bare.getpixel((2, 2))[3] == 0, 'tray bars keep the status colour on a transparent base'
for size in (16, 24, 32, 48, 64, 128, 256):
    assert level_icon(BLUE, tile=True, size=size).size == (size, size)

# 2. The shipped icon files are exactly what the table produces (they are regenerated by brand/make_assets.py).
png = Image.open(ROOT / 'ui' / 'app.png').convert('RGBA')
assert png.tobytes() == level_icon(BLUE, tile=True, size=256).tobytes(), 'ui/app.png is stale: run py brand/make_assets.py'
ico = Image.open(ROOT / 'ui' / 'app.ico')
assert sorted(ico.info['sizes']) == [(n, n) for n in (16, 24, 32, 48, 64, 128, 256)], ico.info['sizes']
for n in (16, 32, 256):
    ico.size = (n, n)
    assert ico.copy().convert('RGBA').tobytes() == level_icon(BLUE, tile=True, size=n).tobytes(), 'ui/app.ico frame %d is stale' % n

# 3. The in-app logo (rail) uses the same geometry.
html = (ROOT / 'ui' / 'index.html').read_text(encoding='utf-8')
symbol = re.search(r'<symbol id="i-listen" viewBox="0 0 64 64">(.*?)</symbol>', html, re.S)
assert symbol, 'the rail logo symbol is missing'
rects = re.findall(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"', symbol.group(1))
assert [(float(x), float(y), float(h)) for x, y, w, h in rects] == [(float(x), float(y), float(h)) for x, y, h, _ in bars]
assert all(float(w) == width for _, _, w, _ in rects)
opacities = re.findall(r'fill-opacity="([\d.]+)"', symbol.group(1))
assert [float(o) for o in opacities] == [b[3] for b in bars if b[3] is not None]

# 4. The product is called Listen wherever a person reads it.
js = (ROOT / 'ui' / 'app.js').read_text(encoding='utf-8')
# Supported Whisper model names remain technology names after the Listen rename.
assert '<title>Listen</title>' in html and 'Whisper' not in html and 'Dictation' not in html
assert 'Whisper' not in re.sub(r'\bWhisper (?:Small|Medium|Large v3(?: Turbo)?)\b', '', js), 'old product name left in ui/app.js'
assert 'options.speech_models' in js and 'options.speech_model_label' in js, 'speech choices must use the real backend model names'
assert 'webview.create_window("Listen"' in source_text and 'pystray.MenuItem("Open Listen"' in source_text
assert 'f"Listen: {s}"' in source_text and 'Whisper recovery' not in source_text and 'Keep Whisper open' not in source_text
card = (ROOT / 'preview_card.py').read_text(encoding='utf-8')
assert 'Whisper' not in card

# 5. If the brand folder is present, its SVGs are the same shape.
brand = ROOT / 'brand'
if (brand / 'listen-mark.svg').exists():
    for name in ('listen-mark.svg', 'listen-mark-light.svg', 'listen-bars.svg'):
        found = re.findall(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)" rx="([\d.]+)"', (brand / name).read_text(encoding='utf-8'))
        geometry = [(float(x), float(y), float(h)) for x, y, w, h, r in found if float(w) == width]
        assert geometry == [(float(x), float(y), float(h)) for x, y, h, _ in bars], name
print('brand: five-bar Level mark, icon files, rail logo and the name Listen all agree')
